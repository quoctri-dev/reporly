"""
Reporly — DOCX Report Exporter
Generates professional Word document from Report dataclass.
"""
import io
import logging
from datetime import datetime

from docx import Document
from docx.shared import Inches, Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn

from src.templates import get_template

logger = logging.getLogger(__name__)


def _hex_to_rgb(hex_color: str) -> RGBColor:
    """Convert hex color string to RGBColor."""
    h = hex_color.lstrip("#")
    return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def _set_cell_shading(cell, hex_color: str):
    """Set background color of a table cell."""
    shading = cell._element.get_or_add_tcPr()
    shading_elm = shading.makeelement(
        qn("w:shd"),
        {qn("w:fill"): hex_color.lstrip("#"), qn("w:val"): "clear"},
    )
    shading.append(shading_elm)


def export_docx(report, template_name: str = "minimal", app_name: str = "Reporly") -> bytes:
    """
    Export Report to DOCX bytes.

    Args:
        report: Report dataclass (from core.models)
        template_name: Template style name
        app_name: App name for branding

    Returns:
        DOCX file as bytes
    """
    tmpl = get_template(template_name)
    doc = Document()

    # Set default font
    style = doc.styles["Normal"]
    font = style.font
    font.name = tmpl.font_body
    font.size = Pt(tmpl.font_size_body)

    # --- Title Page ---
    _add_title_page(doc, report, tmpl)

    # --- Data Overview ---
    _add_data_overview(doc, report.data_profile, tmpl)

    # --- Key Insights ---
    if report.insights:
        _add_insights(doc, report.insights, tmpl)

    # --- Charts ---
    if report.charts:
        _add_charts(doc, report.charts, tmpl)

    # --- Footer ---
    doc.add_paragraph()
    footer_p = doc.add_paragraph()
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer_p.add_run(
        f"Generated by {app_name}  |  {report.generated_at.strftime('%Y-%m-%d %H:%M')}"
    )
    run.font.size = Pt(tmpl.font_size_caption)
    run.font.color.rgb = _hex_to_rgb("#9CA3AF")

    buf = io.BytesIO()
    doc.save(buf)
    docx_bytes = buf.getvalue()

    logger.info("DOCX exported: %.1f KB", len(docx_bytes) / 1024)
    return docx_bytes


