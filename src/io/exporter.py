"""
Reporly — PDF Report Exporter
Generates professional PDF report from Report dataclass.
Uses ReportLab for programmatic control.
"""
import io
import logging
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch, mm
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Image, Table, TableStyle,
    PageBreak, HRFlowable,
)

from src.templates import get_template

logger = logging.getLogger(__name__)


def export_pdf(report, template_name: str = "minimal", app_name: str = "Reporly") -> bytes:
    """
    Export Report to PDF bytes.

    Args:
        report: Report dataclass (from core.models)
        template_name: Template style name
        app_name: App name for branding

    Returns:
        PDF file as bytes
    """
    tmpl = get_template(template_name)
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        topMargin=25 * mm, bottomMargin=20 * mm,
        leftMargin=20 * mm, rightMargin=20 * mm,
    )

    styles = getSampleStyleSheet()
    _add_custom_styles(styles, tmpl)

    story = []

    # --- Cover section ---
    story.extend(_build_cover(report, styles, app_name))
    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E5E7EB")))
    story.append(Spacer(1, 15))

    # --- Data Overview ---
    story.extend(_build_data_overview(report.data_profile, styles))
    story.append(Spacer(1, 15))

    # --- Data Quality Warnings ---
    if report.data_profile.warnings:
        story.extend(_build_warnings(report.data_profile.warnings, styles))
        story.append(Spacer(1, 15))

    # --- AI Insights ---
    if report.insights:
        story.extend(_build_insights(report.insights, styles))
        story.append(Spacer(1, 15))

    # --- Charts ---
    if report.charts:
        story.extend(_build_charts(report.charts, styles))

    # --- Footer ---
    story.append(Spacer(1, 30))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#D1D5DB")))
    story.append(Spacer(1, 8))
    story.append(Paragraph(
        f"Generated by {app_name} · {report.generated_at.strftime('%Y-%m-%d %H:%M')}",
        styles["Footer"],
    ))

    doc.build(story)
    pdf_bytes = buf.getvalue()

    logger.info("PDF exported: %.1f KB", len(pdf_bytes) / 1024)
    return pdf_bytes


