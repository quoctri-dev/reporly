def _add_custom_styles(styles, tmpl):
    """Register custom paragraph styles using template colors/fonts."""
    bold_heading = tmpl.font_heading
    if bold_heading == "Helvetica":
        bold_heading = "Helvetica-Bold"
    elif bold_heading == "Times-Roman":
        bold_heading = "Times-Bold"

    styles.add(ParagraphStyle(
        name="ReportTitle", fontSize=tmpl.font_size_title, leading=tmpl.font_size_title + 6,
        alignment=TA_LEFT, fontName=bold_heading,
        textColor=tmpl.primary_color,
    ))
    styles.add(ParagraphStyle(
        name="Subtitle", fontSize=11, leading=16,
        alignment=TA_LEFT, textColor=tmpl.secondary_color,
        fontName=tmpl.font_body,
    ))
    styles.add(ParagraphStyle(
        name="SectionTitle", fontSize=tmpl.font_size_heading, leading=tmpl.font_size_heading + 4,
        fontName=bold_heading, textColor=tmpl.primary_color,
        spaceBefore=10,
    ))
    styles.add(ParagraphStyle(
        name="SubsectionTitle", fontSize=11, leading=15,
        fontName=bold_heading, textColor=tmpl.secondary_color,
    ))
    styles.add(ParagraphStyle(
        name="BodyCustom", fontSize=tmpl.font_size_body, leading=tmpl.font_size_body + 4,
        textColor="#374151", fontName=tmpl.font_body,
    ))
    styles.add(ParagraphStyle(
        name="InsightBody", fontSize=tmpl.font_size_body - 1, leading=tmpl.font_size_body + 3,
        textColor=tmpl.secondary_color, leftIndent=18, fontName=tmpl.font_body,
    ))
    styles.add(ParagraphStyle(
        name="Footer", fontSize=tmpl.font_size_caption, leading=tmpl.font_size_caption + 2,
        alignment=TA_CENTER, textColor="#9CA3AF", fontName=tmpl.font_body,
    ))
