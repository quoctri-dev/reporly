# Section builders
# ---------------------------------------------------------------------------

def _build_cover(report, styles, app_name: str) -> list:
    """Build cover/title section."""
    return [
        Spacer(1, 40),
        Paragraph(report.title, styles["ReportTitle"]),
        Spacer(1, 8),
        Paragraph(
            f"{report.data_profile.filename} · "
            f"{report.data_profile.rows:,} rows × {report.data_profile.columns} columns",
            styles["Subtitle"],
        ),
        Spacer(1, 30),
    ]


def _build_data_overview(profile, styles) -> list:
    """Build data overview table."""
    elements = [Paragraph("Data Overview", styles["SectionTitle"])]
    elements.append(Spacer(1, 8))

    # Summary stats table
    data = [
        ["Metric", "Value"],
        ["Total Rows", f"{profile.rows:,}"],
        ["Total Columns", str(profile.columns)],
        ["Numeric Columns", str(profile.basic_stats.get("numeric_columns", 0))],
        ["Categorical Columns", str(profile.basic_stats.get("categorical_columns", 0))],
        ["Missing Values", f"{profile.basic_stats.get('total_nulls', 0):,} ({profile.basic_stats.get('null_pct', 0)}%)"],
        ["Memory Size", f"{profile.basic_stats.get('memory_mb', 0)} MB"],
    ]

    table = Table(data, colWidths=[150, 200])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2563EB")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F9FAFB")]),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
    ]))
    elements.append(table)

    # Column details
    elements.append(Spacer(1, 15))
    elements.append(Paragraph("Column Details", styles["SubsectionTitle"]))
    elements.append(Spacer(1, 5))

    col_data = [["Column", "Type", "Unique", "Nulls", "Sample"]]
    for ci in profile.column_info[:20]:  # Max 20 columns in table
        sample = ", ".join(str(v) for v in ci.sample_values[:3])
        if len(sample) > 40:
            sample = sample[:37] + "..."
        col_data.append([
            ci.name[:25], ci.dtype, str(ci.unique_count),
            f"{ci.null_pct}%", sample,
        ])

    col_table = Table(col_data, colWidths=[100, 70, 50, 50, 180])
    col_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#374151")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F9FAFB")]),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
    ]))
    elements.append(col_table)

    return elements


def _build_warnings(warnings: list[str], styles) -> list:
    """Build data quality warnings section."""
    elements = [Paragraph("⚠ Data Quality Notes", styles["SectionTitle"])]
    elements.append(Spacer(1, 5))
    for w in warnings:
        elements.append(Paragraph(f"• {w}", styles["BodyCustom"]))
    return elements


def _build_insights(insights: list, styles) -> list:
    """Build AI insights section."""
    elements = [Paragraph("Key Insights", styles["SectionTitle"])]
    elements.append(Spacer(1, 8))

    importance_colors = {"high": "#DC2626", "medium": "#D97706", "low": "#059669"}

    for i, insight in enumerate(insights, 1):
        color = importance_colors.get(insight.importance, "#6B7280")
        elements.append(Paragraph(
            f'<font color="{color}">●</font> '
            f'<b>{i}. {insight.title}</b> '
            f'<font color="#9CA3AF" size="8">[{insight.importance}]</font>',
            styles["BodyCustom"],
        ))
        elements.append(Paragraph(insight.description, styles["InsightBody"]))
        elements.append(Spacer(1, 8))

    return elements


def _build_charts(charts: list[bytes], styles) -> list:
    """Embed chart images in PDF."""
    elements = [Paragraph("Visualizations", styles["SectionTitle"])]
    elements.append(Spacer(1, 10))

    for chart_bytes in charts:
        img_buf = io.BytesIO(chart_bytes)
        img = Image(img_buf, width=450, height=280)
        elements.append(img)
        elements.append(Spacer(1, 15))

    return elements


